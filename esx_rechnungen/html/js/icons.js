const SVG_NS = 'http://www.w3.org/2000/svg';

/**
 * Erstellt ein SVG-Icon-Element (zuverlässig in FiveM CEF)
 */
function createIconElement(name, size = 18, className = '') {
    const paths = ICON_PATHS[name];
    if (!paths) return null;

    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('class', ('icon ' + (className || '')).trim());
    svg.setAttribute('width', String(size));
    svg.setAttribute('height', String(size));
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('aria-hidden', 'true');

    const parser = document.createElement('div');
    parser.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg">' + paths + '</svg>';
    const tempSvg = parser.firstElementChild;

    if (tempSvg) {
        while (tempSvg.firstChild) {
            svg.appendChild(tempSvg.firstChild);
        }
    }

    return svg;
}

/**
 * Gibt Icon als HTML-String zurück (für Templates)
 */
function icon(name, size = 18, className = '') {
    const el = createIconElement(name, size, className);
    if (!el) return '';
    return el.outerHTML;
}

/**
 * Setzt ein Icon in ein DOM-Element
 */
function setIconElement(target, name, size = 18) {
    if (!target) return;
    target.innerHTML = '';
    const iconEl = createIconElement(name, size);
    if (iconEl) {
        target.appendChild(iconEl);
    }
}

/**
 * Rendert alle [data-icon] Platzhalter im DOM
 */
function injectIcons(root) {
    const scope = root || document;

    scope.querySelectorAll('[data-icon]').forEach(function(el) {
        const name = el.getAttribute('data-icon');
        const size = parseInt(el.getAttribute('data-size') || '18', 10);
        setIconElement(el, name, size);
    });

    const headerLogo = document.getElementById('header-logo');
    if (headerLogo) {
        setIconElement(headerLogo, 'receipt', 22);
    }

    document.querySelectorAll('.btn-close').forEach(function(btn) {
        setIconElement(btn, 'x', 16);
    });
}

// Global verfügbar machen
window.icon = icon;
window.createIconElement = createIconElement;
window.setIconElement = setIconElement;
window.injectIcons = injectIcons;

// Sofort rendern wenn DOM bereit
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() { injectIcons(); });
} else {
    injectIcons();
}
