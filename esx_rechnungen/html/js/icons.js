const SVG_NS = 'http://www.w3.org/2000/svg';

function createIconElement(name, size) {
    const paths = ICON_PATHS[name];
    if (!paths) return null;
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('class', 'icon');
    svg.setAttribute('width', String(size || 18));
    svg.setAttribute('height', String(size || 18));
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    const p = document.createElement('div');
    p.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg">' + paths + '</svg>';
    const t = p.firstElementChild;
    while (t && t.firstChild) svg.appendChild(t.firstChild);
    return svg;
}

function icon(name, size) {
    const el = createIconElement(name, size);
    return el ? el.outerHTML : '';
}

function setIcon(el, name, size) {
    if (!el) return;
    el.innerHTML = '';
    const i = createIconElement(name, size);
    if (i) el.appendChild(i);
}

window.icon = icon;
window.setIcon = setIcon;
window.createIconElement = createIconElement;
